export function getAvatarUrl(seed: string): string {
  const cleanSeed = (seed || "Felix").trim()
  return `https://api.dicebear.com/7.x/notionists/svg?seed=${encodeURIComponent(cleanSeed)}&backgroundColor=ffffff`
}

export function parseParticipantAvatar(
  metadata?: string,
  fallbackIdentity: string = "Felix"
): string {
  if (metadata) {
    try {
      const parsed = JSON.parse(metadata)
      if (parsed.avatar && typeof parsed.avatar === "string") {
        return parsed.avatar
      }
    } catch {}
  }
  return fallbackIdentity || "Felix"
}
